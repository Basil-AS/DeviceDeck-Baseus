/// Return all app-configured variants matching a display or BLE name. Exact, case-insensitive.
pub fn find_by_name(name: &str) -> impl Iterator<Item = &'static DeviceProfile> + '_ {
    BASEUS_INTELLIGENT_218_EU
        .iter()
        .filter(move |p| p.name.eq_ignore_ascii_case(name.trim()))
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn includes_requested_models_and_profiles() {
        for name in [
            "Blade 2",
            "Blade 2-140",
            "Bowie 30",
            "Bowie MF1",
            "Bass EP10 Pro",
        ] {
            let p = find_by_name(name)
                .next()
                .unwrap_or_else(|| panic!("missing {name}"));
            assert_eq!(p.service_uuid, "53527aa4-29f7-ae11-4e74-997334782568");
            assert_eq!(p.write_uuid, "ee684b1a-1e9b-ed3e-ee55-f894667e92ac");
            assert_eq!(p.notify_uuid, "654b749c-e37f-ae1f-ebab-40ca133e3690");
        }
    }
    #[test]
    fn distinguishes_energy_storage_from_shared_unknown_group() {
        assert_eq!(
            find_by_name("Blade 2").next().unwrap().family,
            DeviceFamily::SharedProfileUnknown
        );
        assert_eq!(
            find_by_name("Baseus PPS140").next().unwrap().family,
            DeviceFamily::EnergyStorage
        );
    }
}
